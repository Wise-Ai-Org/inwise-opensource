// Real Electron/IPC + disk persistence, with transcription/AI replaced by deterministic failures.
const { app, BrowserWindow, dialog } = require('electron');
const fs = require('fs');
const os = require('os');
const path = require('path');
const assert = require('assert/strict');
const restartArg = process.argv.find(x=>x.startsWith('--restart-state='));
const prior = restartArg ? JSON.parse(fs.readFileSync(restartArg.split('=')[1], 'utf8')) : null;
const scratch = prior ? prior.scratch : fs.mkdtempSync(path.join(os.tmpdir(), 'inwise-recovery-test-'));
app.setPath('userData', scratch);
app.setName('Inwise recording recovery test');
process.argv.push('--hidden');
dialog.showSaveDialog=async()=>({canceled:false,filePath:path.join(scratch,'exported-audio.webm')});
let transcriptionFails = true;
let insightsFail = true;
const transcript = 'We agreed to review the customer onboarding flow tomorrow. Alex will prepare the draft and share it with the team before the next planning meeting.';
const transcriber = require('../dist/main/transcriber');
transcriber.transcribeAudio = async () => { if (transcriptionFails) throw new Error('injected speech service failure'); return transcript; };
transcriber.transcribeAudioDetailed = async () => ({transcript, metadata:{provider:'synthetic'}});
const extractor = require('../dist/main/extractor');
extractor.extractInsights = async () => { if (insightsFail) throw new Error('injected AI failure'); return { summary: 'Synthetic test summary', actionItems: [], decisions: [], blockers: [] }; };
app.on('browser-window-created', (_e, win) => { win.show = () => {}; win.focus = () => {}; });
require('../dist/main/main');
app.whenReady().then(async () => {
  await new Promise(r => setTimeout(r, 1500));
  const win = new BrowserWindow({ show: false, webPreferences: { nodeIntegration: true, contextIsolation: false } });
  await win.loadURL('data:text/html,<body>Recovery tests</body>');
  const invoke = (channel, ...args) => win.webContents.executeJavaScript(`require('electron').ipcRenderer.invoke(${JSON.stringify(channel)}, ...${JSON.stringify(args)})`);
  const results = [];
  if (prior) {
    const meeting = await invoke('db:getMeeting', prior.meetingId);
    assert.equal(meeting.status, 'error');
    assert.equal(meeting.recordingFailure.stage, 'insights');
    assert.equal(meeting.transcript, transcript);
    assert.equal(fs.existsSync(meeting.recordingRecovery.audioPath), true);
    console.log('Restart recovery passed: interrupted insights, transcript, and audio recovered from disk');
    app.exit(0); return;
  }
  // Permission/disk failure: a file occupies the recordings-directory path.
  fs.writeFileSync(path.join(scratch, 'recordings'), 'blocked');
  const blocked = await invoke('voice:save-capture', [1,2,3], 1, 'audio/webm');
  assert.equal(blocked.ok, false); results.push('disk/save failure reported without claiming audio was saved');
  fs.unlinkSync(path.join(scratch, 'recordings'));
  const saved = await invoke('voice:save-capture', [1,2,3,4], 2, 'audio/webm',null,blocked.meetingId);
  assert.equal(saved.ok, true);
  assert.equal(saved.meetingId,blocked.meetingId);
  results.push('save retry reuses the failed recording rather than duplicating it');
  await invoke('recording:failure', saved.meetingId, 'decode');
  let meeting = await invoke('db:getMeeting', saved.meetingId);
  assert.equal(meeting.recordingFailure.stage, 'decode');
  assert.deepEqual([...fs.readFileSync(meeting.recordingRecovery.audioPath)], [1,2,3,4]);
  results.push('decode failure retains original bytes and durable recovery metadata');
  assert.equal((await invoke('recording:export',saved.meetingId)).ok,true);
  assert.deepEqual([...fs.readFileSync(path.join(scratch,'exported-audio.webm'))],[1,2,3,4]);
  results.push('export writes the original captured bytes without conversion');
  const wav = Buffer.alloc(44 + 32000);
  wav.write('RIFF'); wav.writeUInt32LE(wav.length-8,4); wav.write('WAVE',8); wav.write('fmt ',12); wav.writeUInt32LE(16,16); wav.writeUInt16LE(1,20);wav.writeUInt16LE(1,22);wav.writeUInt32LE(16000,24);wav.writeUInt32LE(32000,28);wav.writeUInt16LE(2,32);wav.writeUInt16LE(16,34);wav.write('data',36);wav.writeUInt32LE(32000,40);
  const failed = await invoke('voice:transcribe', [...wav], 1, saved.meetingId);
  assert.equal(failed.ok, false);
  meeting = await invoke('db:getMeeting', saved.meetingId);
  assert.equal(meeting.recordingFailure.stage, 'transcribing');
  assert.equal(fs.existsSync(meeting.recordingRecovery.audioPath), true);
  results.push('transcription failure preserves WAV and the same recording ID');
  transcriptionFails = false;
  const transcribed = await invoke('voice:transcribe', [...wav], 1, saved.meetingId);
  assert.equal(transcribed.ok, true);
  const insightFailure = await invoke('recording:retry', saved.meetingId);
  assert.equal(insightFailure.ok, false);
  meeting = await invoke('db:getMeeting', saved.meetingId);
  assert.equal(meeting.transcript, transcript);
  assert.equal(meeting.recordingFailure.stage, 'insights');
  results.push('insight failure preserves transcript and reports its stage');
  insightsFail = false;
  const recovered = await invoke('recording:retry', saved.meetingId);
  assert.equal(recovered.ok, true);
  meeting = await invoke('db:getMeeting', saved.meetingId);
  assert.equal(meeting.status, 'processed'); assert.equal(meeting.recordingFailure, null);
  assert.equal(meeting.insights.summary, 'Synthetic test summary');
  results.push('retry recovers the same recording and clears stale failure state');
  // Exercise the actual desktop meeting pipeline and its user-visible status.
  const main = BrowserWindow.getAllWindows().find(w=>w.id!==win.id);
  await main.webContents.executeJavaScript("window.testRecordingStatuses=[]; window.inwiseAPI.on('recording:status',s=>window.testRecordingStatuses.push(s.status))");
  insightsFail = true;
  const desktopCapture=await invoke('voice:save-capture',[1,2,3,4],1,'audio/webm',{title:'Synthetic desktop recovery test',stereo:false,attendees:[],recoveryId:'${desktopCapture.meetingId}'});
  assert.equal(desktopCapture.ok,true);
  await win.webContents.executeJavaScript(`require('electron').ipcRenderer.send('recording:audio-data', {buffer:new Uint8Array(${JSON.stringify([...wav])}),title:'Synthetic desktop recovery test',stereo:false,attendees:[]})`);
  let desktop;
  for(let i=0;i<200;i++){
    desktop=(await invoke('db:getMeetings')).find(m=>m.title==='Synthetic desktop recovery test');
    if(desktop?.recordingFailure?.stage==='insights')break;
    await new Promise(r=>setTimeout(r,100));
  }
  assert.equal(desktop?._id,desktopCapture.meetingId);
  assert.equal(desktop?.status,'error'); assert.equal(desktop?.transcript,transcript);
  await new Promise(r=>setTimeout(r,100));
  const statuses=await main.webContents.executeJavaScript('window.testRecordingStatuses');
  assert.ok(statuses.includes('error')); assert.ok(!statuses.includes('done'));
  results.push('desktop insight failure emits error, never done, and preserves the transcript');
  insightsFail=false;
  assert.equal((await invoke('recording:retry',desktop._id)).ok,true);
  results.push('desktop insights retry recovers without re-transcribing');
  const dbLines = fs.readFileSync(path.join(scratch,'meetings.db'),'utf8');
  assert.ok(dbLines.includes(saved.meetingId));
  results.push('record persisted on disk for restart recovery');
  console.log(JSON.stringify({passed:true,results},null,2));
  fs.mkdirSync(path.join(__dirname,'../artifacts'),{recursive:true});
  fs.writeFileSync(path.join(__dirname,'../artifacts/recording-recovery-tests.json'),JSON.stringify({passed:true,results},null,2));
  await require('../dist/main/database').updateMeetingStatus(saved.meetingId, 'processing');
  fs.writeFileSync(path.join(__dirname,'../artifacts/restart-test-state.json'),JSON.stringify({scratch,meetingId:saved.meetingId}));
  app.exit(0);
}).catch(e => { console.error(e); app.exit(1); });
